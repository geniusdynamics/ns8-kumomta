--[[
  KumoMTA policy of ns8-kumomta.

  Generated by the configure-module action of the NethServer 8 module:
  do not edit, changes are overwritten. Settings come from the module UI.

  - INIT holds the settings read only by the init event (listeners, HTTP
    API, logs): changing them restarts kumod.
  - The TOML files next to this one hold everything else. They are read
    through kumo.memoize with invalidate_with_epoch, so a configuration
    epoch bump (POST /api/admin/bump-config-epoch, done by the module after
    each change, or the file monitor of KumoMTA) applies them without
    dropping connections.
]]

local kumo = require 'kumo'
