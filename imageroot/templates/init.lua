local shaping = require 'policy-extras.shaping'
local listener_domains = require 'policy-extras.listener_domains'
local sources = require 'policy-extras.sources'
local log_hooks = require 'policy-extras.log_hooks'

local POLICY = '/opt/kumomta/etc/policy'
local SECRETS = '/opt/kumomta/etc/secrets'

--@@GENERATED@@

-- Data files, cached until the next configuration epoch
local load_toml = kumo.memoize(function(path)
  local ok, data = pcall(kumo.toml_load, path)
  if not ok then
    kumo.log_error(string.format('ns8: cannot read %s: %s', path, data))
    return {}
  end
  return data
end, {
  name = 'ns8_toml_files',
  ttl = '5 minutes',
  capacity = 32,
  invalidate_with_epoch = true,
})

local function policy_data(name)
  return load_toml(POLICY .. '/' .. name)
end

-- Trusted networks: relaying without SMTP AUTH
local trusted_map = kumo.memoize(function()
  local map = {}
  for _, net in ipairs(policy_data('relay_hosts.toml').networks or {}) do
    map[net] = true
  end
  return kumo.cidr.make_map(map)
end, {
  name = 'ns8_trusted_networks',
  ttl = '5 minutes',
  capacity = 1,
  invalidate_with_epoch = true,
})

local function peer_ip(meta_source)
  local received_from = meta_source:get_meta 'received_from'
  if not received_from then
    return nil
  end
  local ip, _port = utils.split_ip_port(received_from)
  return ip
end

local function is_trusted(meta_source)
  if meta_source:get_meta 'authz_id' then
    return true
  end
  local ip = peer_ip(meta_source)
  if ip and trusted_map()[ip] then
    return true
  end
  return false
end

-- Integration credentials of the sending platforms (hashes, tenant,
-- scopes, rate): a 0600 file of the secrets directory
local function integrations()
  return load_toml(SECRETS .. '/integrations.toml').integration or {}
end

local function integration_allows(name, scope)
  local integ = integrations()[name]
  if not integ then
    return nil
  end
  for _, s in ipairs(integ.scopes or {}) do
    if s == scope then
      return integ
    end
  end
  return nil
end

local function check_password(entry, password)
  return entry ~= nil
    and password ~= nil
    and password ~= ''
    and kumo.digest.sha256(entry.salt .. password).hex == entry.sha256
end

-- Messages of an integration: the From domain must be a sending domain
-- of this MTA, owned by the integration or by the administrator, and
-- verified unless require_verified_domains is off. The tenant of the
-- integration, if any, wins over the X-Tenant header.
local function apply_integration_policy(msg, name, integ)
  local from = msg:from_header()
  if not from then
    kumo.reject(550, '5.7.1 a From header is required')
  end
  local domain = string.lower(from.domain)
  local entry = (policy_data('dkim_data.toml').domain or {})[domain]
  if not entry then
    kumo.reject(550, string.format('5.7.1 %s is not a sending domain of this server', domain))
  end
  if entry.owner and entry.owner ~= '' and entry.owner ~= name then
    kumo.reject(550, string.format('5.7.1 %s belongs to another integration', domain))
  end
  local platform = policy_data('platform.toml')
  if platform.require_verified_domains ~= false and not entry.verified then
    kumo.reject(550, string.format('5.7.1 sending domain %s is not verified', domain))
  end
  local tenant = integ.tenant
  if (not tenant or tenant == '') and entry.tenant and entry.tenant ~= '' then
    tenant = entry.tenant
  end
  if tenant and tenant ~= '' then
    msg:set_meta('tenant', tenant)
  end
end

-- X-Tenant and X-Campaign headers select the tenant and campaign of the
-- message (KumoMTA queue name campaign:tenant@domain), and are removed.
-- X-Message-Ref is kept and logged (meta x_message_ref) for correlation.
local function import_tenant_campaign(msg)
  msg:import_x_headers { 'x-tenant', 'x-campaign', 'x-message-ref' }
  local tenant = msg:get_meta 'x_tenant'
  local campaign = msg:get_meta 'x_campaign'
  if tenant and tenant ~= '' then
    msg:set_meta('tenant', tenant)
  end
  if campaign and campaign ~= '' then
    msg:set_meta('campaign', campaign)
  end
  msg:remove_x_headers { 'x-tenant', 'x-campaign' }
end

local get_inbound_domain = listener_domains:setup { POLICY .. '/listener_domains.toml' }
sources:setup { POLICY .. '/sources.toml' }

-- Traffic shaping, with the automation daemons (tsa-daemon) when INIT.tsa
-- lists them: the log records go to every daemon of the cluster, the
-- shaping overrides come from the subscribed one. The lists are read at
-- startup only (configure_log_hook happens in the init event), so a peer
-- joining or leaving restarts kumod; docs/cluster.md.
local shaper = shaping:setup_with_automation {
  no_default_files = false,
  extra_files = { POLICY .. '/shaping.toml' },
  publish = INIT.tsa and INIT.tsa.publish or nil,
  subscribe = INIT.tsa and INIT.tsa.subscribe or nil,
}

if INIT.webhook then
  local types = {}
  for _, t in ipairs(INIT.webhook_record_types) do
    types[t] = true
  end
  log_hooks:new {
    name = 'ns8_webhook',
    log_parameters = {
      headers = { 'Subject', 'Message-ID' },
      meta = { 'tenant', 'campaign', 'extra', 'x_message_ref' },
    },
    filter = function(msg, hook_name)
      local record = msg:get_meta 'log_record'
      if record and not types[record.type] then
        -- filtered out
        return true
      end
      return false
    end,
    constructor = function(domain, tenant, campaign)
      local connection = {}
      local client = kumo.http.build_client {}
      function connection:send(message)
        local cfg = policy_data('webhook.toml')
        local request = client
          :post(cfg.url)
          :header('Content-Type', 'application/json')
          :body(message:get_data())
        local body = message:get_data()
        if cfg.token then
          local token = kumo.secrets.load(KEYS.webhook_token)
          request = request:header('Authorization', 'Bearer ' .. token)
        end
        if cfg.signing then
          -- HMAC-SHA256 of "<timestamp>.<body>", see docs/webhooks.md
          local ts = tostring(os.time())
          local mac = kumo.digest.hmac_sha256(KEYS.webhook_signing_secret, ts .. '.' .. body)
          request = request:header('X-KumoMTA-Signature', string.format('t=%s,v1=%s', ts, mac.hex))
        end
        local response = request:send()
        local disposition = string.format(
          '%d %s: %s',
          response:status_code(),
          response:status_reason(),
          response:text()
        )
        if response:status_is_success() then
          return disposition
        end
        -- 4xx: retried later, until the record expires
        kumo.reject(400, disposition)
      end
      return connection
    end,
  }
end

kumo.on('init', function()
  kumo.define_spool {
    name = 'data',
    path = '/var/spool/kumomta/data',
  }
  kumo.define_spool {
    name = 'meta',
    path = '/var/spool/kumomta/meta',
  }

  -- Shared throttles and connection limits of the cluster. KumoMTA pings
  -- the store here and does not start if it does not answer: the module
  -- checks it first (ExecStartPre) and renders local throttles instead.
  if INIT.redis then
    local params = {
      node = INIT.redis.node,
      cluster = INIT.redis.cluster,
      connect_timeout = '5 seconds',
      response_timeout = '3 seconds',
      wait_timeout = '5 seconds',
    }
    if INIT.redis.username then
      params.username = INIT.redis.username
    end
    if KEYS.cluster_redis_password then
      params.password = kumo.secrets.load(KEYS.cluster_redis_password)
    end
    kumo.configure_redis_throttles(params)
  end

  if INIT.tsa then
    shaper.setup_publish()
  end

  kumo.configure_local_logs {
    log_dir = '/var/log/kumomta',
    max_segment_duration = '1 minute',
    meta = { 'tenant', 'campaign', 'extra', 'x_message_ref' },
  }

  -- bounce_classification of the Bounce, TransientFailure and OOB records
  kumo.configure_bounce_classifier {
    files = { '/opt/kumomta/share/bounce_classifier/iana.toml' },
  }

  -- The admin API listens on the loopback only and every request needs
  -- HTTP basic authentication: no trusted hosts
  kumo.start_http_listener {
    listen = INIT.http_listen,
    trusted_hosts = { '0.0.0.0/32' },
  }

  for _, listener in ipairs(INIT.listeners) do
    kumo.start_esmtp_listener {
      listen = listener.listen,
      hostname = INIT.hostname,
      -- relaying is decided by get_listener_domain below. An empty Lua
      -- table would be read as a map: list an address no client has
      relay_hosts = { '0.0.0.0/32' },
      max_message_size = INIT.max_message_size,
      tls_certificate = INIT.tls_certificate,
      tls_private_key = INIT.tls_private_key,
    }
  end

  kumo.set_config_monitor_globs {
    POLICY .. '/*.{lua,toml}',
    SECRETS .. '/*.toml',
  }
end)

