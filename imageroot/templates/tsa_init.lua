--[[
  tsa-daemon policy of ns8-kumomta (traffic shaping automation).

  Generated by the configure-module action of the NethServer 8 module:
  do not edit, changes are overwritten.

  The daemon receives the log records of kumod (publish_log_v1), applies
  the automation rules of the shaping files and serves the resulting
  overrides (get_config_v1) and suspensions (subscribe_event_v1). kumod
  sends no credentials: access is granted by source address only
  (trusted_hosts: loopback for standalone, or the exact VPN addresses
  of verified KumoMTA peers using the same throttle store).
]]

local tsa = require 'tsa'
local kumo = require 'kumo'

--@@GENERATED@@

kumo.on('tsa_init', function()
  -- State of the daemon, on its own volume (kumomta-tsa)
  tsa.configure_tsa_db_path '/var/spool/kumomta/tsa.db'
  tsa.start_http_listener {
    listen = TSA.listen,
    trusted_hosts = TSA.trusted_hosts,
  }
end)

local cached_load_shaping_data = kumo.memoize(kumo.shaping.load, {
  name = 'tsa_load_shaping_data',
  ttl = '5 minutes',
  capacity = 4,
})

-- The same shaping files as kumod: the KumoMTA defaults (with the
-- automation rules of the large mailbox providers) and the per-domain
-- settings of the module
kumo.on('tsa_load_shaping_data', function()
  return cached_load_shaping_data {
    '/opt/kumomta/share/policy-extras/shaping.toml',
    '/opt/kumomta/etc/policy/shaping.toml',
  }
end)
