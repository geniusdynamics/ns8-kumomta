--[[
  KumoMTA policy of ns8-kumomta.

  Generated by the configure-module action of the NethServer 8 module:
  do not edit, changes are overwritten. Settings come from the module UI.

  - INIT holds the settings read only by the init event (listeners, HTTP
    API, logs): changing them restarts kumod.
  - The TOML files next to this one hold everything else. They are read
    through kumo.memoize with invalidate_with_epoch, so a configuration
    epoch bump (POST /api/admin/bump-config-epoch, done by the module after
    each change, or the file monitor of KumoMTA) applies them without
    dropping connections.
]]

local kumo = require 'kumo'
local utils = require 'policy-extras.policy_utils'
local shaping = require 'policy-extras.shaping'
local listener_domains = require 'policy-extras.listener_domains'
local sources = require 'policy-extras.sources'
local log_hooks = require 'policy-extras.log_hooks'

local POLICY = '/opt/kumomta/etc/policy'
local SECRETS = '/opt/kumomta/etc/secrets'

--@@GENERATED@@

-- Data files, cached until the next configuration epoch
local load_toml = kumo.memoize(function(path)
  local ok, data = pcall(kumo.toml_load, path)
  if not ok then
    kumo.log_error(string.format('ns8: cannot read %s: %s', path, data))
    return {}
  end
  return data
end, {
  name = 'ns8_toml_files',
  ttl = '5 minutes',
  capacity = 32,
  invalidate_with_epoch = true,
})

local function policy_data(name)
  return load_toml(POLICY .. '/' .. name)
end

-- Trusted networks: relaying without SMTP AUTH
local trusted_map = kumo.memoize(function()
  local map = {}
  for _, net in ipairs(policy_data('relay_hosts.toml').networks or {}) do
    map[net] = true
  end
  return kumo.cidr.make_map(map)
end, {
  name = 'ns8_trusted_networks',
  ttl = '5 minutes',
  capacity = 1,
  invalidate_with_epoch = true,
})

local function peer_ip(meta_source)
  local received_from = meta_source:get_meta 'received_from'
  if not received_from then
    return nil
  end
  local ip, _port = utils.split_ip_port(received_from)
  return ip
end

local function is_trusted(meta_source)
  if meta_source:get_meta 'authz_id' then
    return true
  end
  local ip = peer_ip(meta_source)
  if ip and trusted_map()[ip] then
    return true
  end
  return false
end

local get_inbound_domain = listener_domains:setup { POLICY .. '/listener_domains.toml' }
sources:setup { POLICY .. '/sources.toml' }

local shaper = shaping:setup_with_automation {
  no_default_files = false,
  extra_files = { POLICY .. '/shaping.toml' },
}

if INIT.webhook then
  local types = {}
  for _, t in ipairs(INIT.webhook_record_types) do
    types[t] = true
  end
  log_hooks:new {
    name = 'ns8_webhook',
    log_parameters = {
      headers = { 'Subject', 'Message-ID' },
    },
    filter = function(msg, hook_name)
      local record = msg:get_meta 'log_record'
      if record and not types[record.type] then
        -- filtered out
        return true
      end
      return false
    end,
    constructor = function(domain, tenant, campaign)
      local connection = {}
      local client = kumo.http.build_client {}
      function connection:send(message)
        local cfg = policy_data('webhook.toml')
        local request = client
          :post(cfg.url)
          :header('Content-Type', 'application/json')
          :body(message:get_data())
        if cfg.token then
          local token = kumo.secrets.load(KEYS.webhook_token)
          request = request:header('Authorization', 'Bearer ' .. token)
        end
        local response = request:send()
        local disposition = string.format(
          '%d %s: %s',
          response:status_code(),
          response:status_reason(),
          response:text()
        )
        if response:status_is_success() then
          return disposition
        end
        -- 4xx: retried later, until the record expires
        kumo.reject(400, disposition)
      end
      return connection
    end,
  }
end

kumo.on('init', function()
  kumo.define_spool {
    name = 'data',
    path = '/var/spool/kumomta/data',
  }
  kumo.define_spool {
    name = 'meta',
    path = '/var/spool/kumomta/meta',
  }

  kumo.configure_local_logs {
    log_dir = '/var/log/kumomta',
    max_segment_duration = '1 minute',
  }

  -- The admin API listens on the loopback only and every request needs
  -- HTTP basic authentication: no trusted hosts
  kumo.start_http_listener {
    listen = INIT.http_listen,
    trusted_hosts = { '0.0.0.0/32' },
  }

  for _, listener in ipairs(INIT.listeners) do
    kumo.start_esmtp_listener {
      listen = listener.listen,
      hostname = INIT.hostname,
      -- relaying is decided by get_listener_domain below. An empty Lua
      -- table would be read as a map: list an address no client has
      relay_hosts = { '0.0.0.0/32' },
      max_message_size = INIT.max_message_size,
      tls_certificate = INIT.tls_certificate,
      tls_private_key = INIT.tls_private_key,
    }
  end

  kumo.set_config_monitor_globs {
    POLICY .. '/*.{lua,toml}',
    SECRETS .. '/*.toml',
  }
end)

-- HTTP API authorization: acl.toml replaces the product default ACL, so
-- that no address is trusted without authentication
local get_acl_map = kumo.memoize(function()
  return kumo.aaa.load_acl_map(POLICY .. '/acl.toml')
end, {
  name = 'ns8_acl_map',
  ttl = '5 minutes',
  capacity = 1,
  invalidate_with_epoch = true,
})

kumo.on('get_acl_definition', function(resource)
  return get_acl_map():get(resource)
end)

kumo.on('pre_init', function()
  kumo.aaa.set_fall_back_to_acl_map(false)
end)

-- HTTP API authentication: the module user, and the optional metrics user
kumo.on('http_server_validate_auth_basic', function(user, password)
  if not password or password == '' then
    return false
  end
  if user == 'ns8-admin' then
    return password == kumo.secrets.load(KEYS.api_password)
  end
  if user == 'metrics' then
    local ok, expected = pcall(kumo.secrets.load, KEYS.metrics_password)
    return ok and expected ~= '' and password == expected
  end
  return false
end)

-- SMTP AUTH PLAIN (only after STARTTLS): salted SHA-256 hashes
kumo.on('smtp_server_auth_plain', function(authz, authc, password, conn_meta)
  if password == '' then
    return false
  end
  local users = load_toml(SECRETS .. '/smtp_users.toml').user or {}
  local entry = users[authc]
  if not entry then
    return false
  end
  if authz ~= authc then
    return false
  end
  return kumo.digest.sha256(entry.salt .. password).hex == entry.sha256
end)

-- Relaying: authenticated clients and trusted networks relay anywhere;
-- anyone else can only send to the inbound domains
kumo.on('get_listener_domain', function(domain, listener, conn_meta)
  if is_trusted(conn_meta) then
    return kumo.make_listener_domain {
      relay_to = true,
    }
  end
  return get_inbound_domain(domain, listener, conn_meta)
end)

-- DKIM signing of the messages of trusted clients
local function dkim_sign(msg)
  local data = policy_data('dkim_data.toml')
  local from = msg:from_header()
  if not from or not data.domain then
    return
  end
  local domain = string.lower(from.domain)
  local entry = data.domain[domain]
  if not entry then
    return
  end
  local base = data.base or {}
  local key
  if base.vault_mount then
    key = {
      vault_mount = base.vault_mount,
      vault_path = string.format(
        '%s/%s/%s',
        base.vault_path_prefix,
        domain,
        entry.selector
      ),
    }
    if base.vault_key then
      key.vault_key = base.vault_key
    end
  else
    key = entry.filename
  end
  local ok, err = pcall(function()
    local signer = kumo.dkim.rsa_sha256_signer {
      domain = domain,
      selector = entry.selector,
      headers = entry.headers or base.headers,
      key = key,
    }
    msg:dkim_sign(signer)
  end)
  if not ok then
    -- Deliver unsigned rather than losing the message
    kumo.log_error(string.format('ns8: DKIM signing for %s failed: %s', domain, err))
  end
end

kumo.on('smtp_server_message_received', function(msg)
  if is_trusted(msg) then
    dkim_sign(msg)
  end
end)

kumo.on('http_message_generated', function(msg)
  dkim_sign(msg)
end)

-- Scheduled queues: retention, inbound routes, smarthost
kumo.on('get_queue_config', function(domain, tenant, campaign, routing_domain)
  local q = policy_data('queues.toml')
  local default = q.default or {}
  local params = {
    egress_pool = default.egress_pool or 'default',
    retry_interval = default.retry_interval,
    max_age = default.max_age,
  }
  local route = (q.route or {})[domain]
  local smarthost = q.smarthost or {}
  if route then
    params.protocol = { smtp = { mx_list = route.mx_list } }
  elseif smarthost.enabled then
    params.protocol = { smtp = { mx_list = smarthost.mx_list } }
  end
  return kumo.make_queue_config(params)
end)

-- Egress paths: traffic shaping, plus port, TLS and authentication of the
-- inbound routes and the smarthost
kumo.on('get_egress_path_config', function(domain, egress_source, site_name)
  local params =
    shaper.get_egress_path_config(domain, egress_source, site_name, true)
  local q = policy_data('queues.toml')
  local route = (q.route or {})[domain]
  local smarthost = q.smarthost or {}
  if route then
    params.smtp_port = route.port
    params.enable_tls = 'OpportunisticInsecure'
  elseif smarthost.enabled then
    params.smtp_port = smarthost.port
    params.enable_tls = smarthost.enable_tls
    if smarthost.username and smarthost.username ~= '' then
      params.smtp_auth_plain_username = smarthost.username
      params.smtp_auth_plain_password = KEYS.smarthost_password
    end
  end
  return kumo.make_egress_path(params)
end)
