-- HTTP API authentication: the module user, and the optional metrics user
kumo.on('http_server_validate_auth_basic', function(user, password)
  if not password or password == '' then
    return false
  end
  if user == 'ns8-admin' then
    return password == kumo.secrets.load(KEYS.api_password)
  end
  if user == 'metrics' then
    local ok, expected = pcall(kumo.secrets.load, KEYS.metrics_password)
    return ok and expected ~= '' and password == expected
  end
  -- Integration credentials: acl.toml grants them /api/inject only
  return check_password(integration_allows(user, 'inject'), password)
end)

-- SMTP AUTH PLAIN (only after STARTTLS): salted SHA-256 hashes
kumo.on('smtp_server_auth_plain', function(authz, authc, password, conn_meta)
  if password == '' then
    return false
  end
  if authz ~= authc then
    return false
  end
  local users = load_toml(SECRETS .. '/smtp_users.toml').user or {}
  local entry = users[authc]
  if entry then
    return check_password(entry, password)
  end
  -- Integration credentials with the smtp scope
  return check_password(integration_allows(authc, 'smtp'), password)
end)

-- Relaying: authenticated clients and trusted networks relay anywhere;
-- anyone else can only send to the inbound domains
kumo.on('get_listener_domain', function(domain, listener, conn_meta)
  -- Return path and feedback domains: bounces (OOB) and ARF reports are
  -- logged as OOB and Feedback records, never relayed
  local platform = policy_data('platform.toml')
  local lower = string.lower(domain)
  if platform.bounce_domain and platform.bounce_domain ~= '' then
    local is_bounce = (lower == string.lower(platform.bounce_domain))
    for _, d in ipairs(platform.return_path_domains or {}) do
      if lower == d then
        is_bounce = true
      end
    end
    if is_bounce then
      return kumo.make_listener_domain {
        log_oob = true,
        log_arf = true,
      }
    end
  end
  if is_trusted(conn_meta) then
    return kumo.make_listener_domain {
      relay_to = true,
    }
  end
  return get_inbound_domain(domain, listener, conn_meta)
end)

-- DKIM signing of the messages of trusted clients
local function dkim_sign(msg)
  local data = policy_data('dkim_data.toml')
  local from = msg:from_header()
  if not from or not data.domain then
    return
  end
  local domain = string.lower(from.domain)
  local entry = data.domain[domain]
  if not entry then
    return
  end
  local base = data.base or {}
  local key
  if base.vault_mount then
    key = {
      vault_mount = base.vault_mount,
      vault_path = string.format(
        '%s/%s/%s',
        base.vault_path_prefix,
        domain,
        entry.selector
      ),
    }
    if base.vault_key then
      key.vault_key = base.vault_key
    end
  else
    key = entry.filename
  end
  local ok, err = pcall(function()
    local signer = kumo.dkim.rsa_sha256_signer {
      domain = domain,
      selector = entry.selector,
      headers = entry.headers or base.headers,
      key = key,
    }
    msg:dkim_sign(signer)
  end)
  if not ok then
    -- Deliver unsigned rather than losing the message
    kumo.log_error(string.format('ns8: DKIM signing for %s failed: %s', domain, err))
  end
end

kumo.on('smtp_server_message_received', function(msg)
  if is_trusted(msg) then
    import_tenant_campaign(msg)
    local authz = msg:get_meta 'authz_id'
    local users = load_toml(SECRETS .. '/smtp_users.toml').user or {}
    if authz and not users[authz] then
      local integ = integration_allows(authz, 'smtp')
      if integ then
        apply_integration_policy(msg, authz, integ)
      end
    end
    dkim_sign(msg)
  end
end)

kumo.on('http_message_generated', function(msg)
  import_tenant_campaign(msg)
  local user = msg:get_meta 'http_auth'
  if user and user ~= 'ns8-admin' then
    local integ = integration_allows(user, 'inject')
    if not integ then
      kumo.reject(550, '5.7.1 not authorized to inject')
    end
    apply_integration_policy(msg, user, integ)
  end
  dkim_sign(msg)
end)

-- Per-tenant sending rate of the integrations (max_message_rate): the
-- messages wait in their scheduled queue instead of being rejected
kumo.on('throttle_insert_ready_queue', function(msg)
  local tenant = msg:get_meta 'tenant'
  if not tenant or tenant == '' then
    return
  end
  for name, integ in pairs(integrations()) do
    if integ.tenant == tenant and integ.max_message_rate and integ.max_message_rate ~= '' then
      kumo
        .make_throttle('ns8-tenant-' .. tenant, integ.max_message_rate)
        :delay_message_if_throttled(msg)
      return
    end
  end
end)

-- Sink mode (testing): the ns8_sink "connection" accepts and discards
-- every message instead of delivering it, and logs a Delivery record, like
-- the KumoMTA smart-sink example. A recipient local part containing
-- "tempfail" or "permfail" simulates a transient failure or a bounce.
kumo.on('ns8_sink', function(domain, tenant, campaign)
  local connection = {}
  function connection:send(message)
    local user = string.lower(message:recipient().user or '')
    if string.find(user, 'tempfail', 1, true) then
      kumo.reject(451, '4.3.0 ns8-kumomta sink: simulated transient failure')
    end
    if string.find(user, 'permfail', 1, true) then
      kumo.reject(550, '5.1.1 ns8-kumomta sink: simulated bounce')
    end
    return 'ns8-kumomta sink: accepted and discarded, not delivered'
  end
  return connection
end)

kumo.on('ns8_discard', function(domain, tenant, campaign)
  local connection = {}
  function connection:send(message)
    return 'ns8-kumomta: log record of a former tsa-daemon peer discarded'
  end
  return connection
end)

-- Scheduled queues: retention, inbound routes, smarthost. The queue
-- configuration follows the configuration epoch, so a change applies to
-- the existing queues at once.
kumo.on('get_queue_config', function(domain, tenant, campaign, routing_domain)
  -- Log records queued for the tsa-daemon of a peer that left the cluster:
  -- the shaping helper no longer owns that queue, discard the records
  -- rather than resolving "<url>.tsa.kumomta" as a mail domain
  if string.sub(domain, -12) == '.tsa.kumomta' then
    return kumo.make_queue_config {
      protocol = { custom_lua = { constructor = 'ns8_discard' } },
      max_age = '1 hour',
    }
  end
  local q = policy_data('queues.toml')
  local default = q.default or {}
  local params = {
    egress_pool = default.egress_pool or 'default',
    retry_interval = default.retry_interval,
    max_age = default.max_age,
    refresh_strategy = 'Epoch',
  }
  if (q.sink or {}).enabled then
    params.protocol = { custom_lua = { constructor = 'ns8_sink' } }
    return kumo.make_queue_config(params)
  end
  local route = (q.route or {})[domain]
  local smarthost = q.smarthost or {}
  if route then
    params.protocol = { smtp = { mx_list = route.mx_list } }
  elseif smarthost.enabled then
    params.protocol = { smtp = { mx_list = smarthost.mx_list } }
  end
  return kumo.make_queue_config(params)
end)

-- Egress paths: traffic shaping, plus port, TLS and authentication of the
-- inbound routes and the smarthost
-- Overall limits of a sending IP (egress source), all destinations
-- together: named limits, shared through the throttle store of a cluster.
-- Only real mail destinations count (not the TSA and webhook log hooks).
local function add_ip_limits(params, domain, egress_source)
  if not string.find(domain, '.', 1, true) or string.sub(domain, -12) == '.tsa.kumomta' then
    return
  end
  local limits = (policy_data('ip_limits.toml').source or {})[egress_source]
  if not limits then
    return
  end
  for key, table_name in pairs {
    rates = 'additional_message_rate_throttles',
    connections = 'additional_connection_limits',
  } do
    for name, value in pairs(limits[key] or {}) do
      params[table_name] = params[table_name] or {}
      params[table_name][name] = value
    end
  end
end

kumo.on('get_egress_path_config', function(domain, egress_source, site_name)
  local params =
    shaper.get_egress_path_config(domain, egress_source, site_name, true)
  add_ip_limits(params, domain, egress_source)
  local q = policy_data('queues.toml')
  local route = (q.route or {})[domain]
  local smarthost = q.smarthost or {}
  if route then
    params.smtp_port = route.port
    params.enable_tls = 'OpportunisticInsecure'
  elseif smarthost.enabled then
    params.smtp_port = smarthost.port
    params.enable_tls = smarthost.enable_tls
    if smarthost.username and smarthost.username ~= '' then
      params.smtp_auth_plain_username = smarthost.username
      params.smtp_auth_plain_password = KEYS.smarthost_password
    end
  end
  return kumo.make_egress_path(params)
end)
